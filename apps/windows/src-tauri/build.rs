// build.rs — minimal build script for Tauri 2.
// Sidecar binaries (mihomo core, wintun.dll) are NOT embedded in
// the Tauri binary; they are manually copied into App/ by scripts/windows/build-portable.ps1.
// create-tauri-app scaffolds an empty build.rs; Tauri's own resource embedding is handled
// via tauri.conf.json `bundle.resources`, so this file stays minimal.
//
// Additional duty: 生成 {OUT_DIR}/region_data.rs 的地区识别数据。
// 手写数据源 resources/region/{aliases,airports}.txt（按行 `展示名\t别名,...`），
// 由此生成为 src/util/region.rs include! 的静态数组代码。改数据文件即可，勿改生成代码。

use std::collections::HashSet;
use std::env;
use std::fs;
use std::path::PathBuf;

fn main() {
    tauri_build::build();
    // tauri-build 只 rerun-if-changed tauri.conf.json / resources，不感知图标文件。
    // 若换图标（icons/icon.ico）不触发 build script 重跑，exe 会继续嵌旧图标。
    // 显式声明，让图标变更能重新嵌入 Windows 资源。
    println!("cargo:rerun-if-changed=icons/icon.ico");
    println!("cargo:rerun-if-changed=icons/icon.icns");
    println!("cargo:rerun-if-changed=icons/32x32.png");
    // Desktop/taskbar cat icons (tray icon 32x32.png 保持不变)
    println!("cargo:rerun-if-changed=icons/cat-32x32.png");
    println!("cargo:rerun-if-changed=icons/cat-128x128.png");
    println!("cargo:rerun-if-changed=icons/cat-256x256.png");
    println!("cargo:rerun-if-changed=icons/cat.icns");
    println!("cargo:rerun-if-changed=icons/cat.ico");
    generate_region_data();
    generate_product_data();
}

// region 数据：resources/region/*.txt → OUT_DIR/region_data.rs。
// 行格式 `展示名\t别名,别名,...`；`#` 开头行与空行忽略。别名顺序即
// 匹配优先级（长别名在前），顺序忠实保留；全局重复别名直接让构建
// 失败（比 cargo test 更早暴露，结果不该依赖表顺序）。
fn generate_region_data() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let aliases_src = manifest.join("resources/region/aliases.txt");
    let airports_src = manifest.join("resources/region/airports.txt");
    println!("cargo:rerun-if-changed=resources/region/aliases.txt");
    println!("cargo:rerun-if-changed=resources/region/airports.txt");

    let aliases_txt = fs::read_to_string(&aliases_src)
        .unwrap_or_else(|e| panic!("read {}: {e}", aliases_src.display()));
    let airports_txt = fs::read_to_string(&airports_src)
        .unwrap_or_else(|e| panic!("read {}: {e}", airports_src.display()));
    // 容忍 BOM（编辑器带 BOM 保存不得悄悄改变首展示名）。
    let aliases_txt = aliases_txt.trim_start_matches('\u{feff}');
    let airports_txt = airports_txt.trim_start_matches('\u{feff}');

    let mut out = String::new();
    out.push_str(&format!(
        "// @@generated by build.rs from {} / {} — do not edit by hand.\n",
        aliases_src.display(),
        airports_src.display()
    ));
    out.push_str("static REGION_TABLE: &[RegionRule] = &[\n");
    let mut seen = HashSet::new();
    let mut rule_count = 0usize;
    for (n, line) in aliases_txt.lines().enumerate() {
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let line_no = n + 1;
        let fail =
            |msg: String| -> String { format!("{}:{line_no}: {msg}", aliases_src.display()) };
        let (display, aliases) = line
            .split_once('\t')
            .ok_or_else(|| fail("<display>\\t<alias,...> expected".into()))
            .unwrap_or_else(|e| panic!("{}", e));
        let display = display.trim();
        if display.is_empty() {
            panic!("{}", fail("display is empty".into()));
        }
        let rendered: Vec<String> = aliases
            .split(',')
            .map(str::trim)
            .filter(|a| !a.is_empty())
            .map(|alias| {
                if !seen.insert(alias.to_string()) {
                    panic!("{}", fail(format!("duplicate alias '{alias}'")));
                }
                format!("\"{}\"", escape(alias))
            })
            .collect();
        out.push_str(&format!(
            "    RegionRule {{ display: \"{}\", aliases: &[{}] }},\n",
            escape(display),
            rendered.join(", ")
        ));
        rule_count += 1;
    }
    if rule_count == 0 {
        panic!("no regions parsed from {}", aliases_src.display());
    }
    out.push_str("];\n\n");

    out.push_str("static AIRPORT_CODES: &[(&str, &str)] = &[\n");
    let mut airport_count = 0usize;
    let mut airport_seen = HashSet::new();
    for (n, line) in airports_txt.lines().enumerate() {
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let line_no = n + 1;
        let fail =
            |msg: String| -> String { format!("{}:{line_no}: {msg}", airports_src.display()) };
        let (code, display) = line
            .split_once('\t')
            .ok_or_else(|| fail("<code>\\t<display> expected".into()))
            .unwrap_or_else(|e| panic!("{}", e));
        let (code, display) = (code.trim(), display.trim());
        if code.is_empty() || code.len() != 3 || !code.chars().all(|c| c.is_ascii_alphanumeric()) {
            panic!("{}", fail(format!("invalid IATA code '{code}'")));
        }
        if display.is_empty() {
            panic!("{}", fail("display is empty".into()));
        }
        if !airport_seen.insert(code.to_string()) {
            panic!("{}", fail(format!("duplicate airport code '{code}'")));
        }
        out.push_str(&format!(
            "    (\"{}\", \"{}\"),\n",
            escape(code),
            escape(display)
        ));
        airport_count += 1;
    }
    out.push_str("];\n");

    if airport_count == 0 {
        panic!("no airports parsed from {}", airports_src.display());
    }

    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR"));
    fs::write(out_dir.join("region_data.rs"), out).expect("write region_data.rs");
}

// Rust 字符串字面量安全转义（数据里出现引号/反斜杠/控制字符也不生成非法代码）。
fn escape(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    for c in s.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if (c as u32) < 0x20 => out.push_str(&format!("\\u{{{:x}}}", c as u32)),
            c => out.push(c),
        }
    }
    out
}

// Product 级共享常量：shared/product.json → OUT_DIR/product_data.rs。
// 组名与内置规则集名是两端（Windows / Android）必须严格一致的产品契约；
// 单一来源在此 JSON，Windows 构建期由本函数生成 Rust 常量，禁止在
// src 里手写字面量副本（防两端漂移，D4-4）。
fn generate_product_data() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let src = manifest.join("../../../shared/product.json");
    println!("cargo:rerun-if-changed=../../../shared/product.json");

    let text = fs::read_to_string(&src).unwrap_or_else(|e| panic!("read {}: {e}", src.display()));
    let text = text.trim_start_matches('\u{feff}');
    let doc: serde_json::Value =
        serde_json::from_str(text).unwrap_or_else(|e| panic!("parse {}: {e}", src.display()));

    let groups = doc
        .get("proxy_groups")
        .and_then(|v| v.as_object())
        .unwrap_or_else(|| panic!("{}: missing proxy_groups object", src.display()));
    let rule_sets = doc
        .get("rule_sets")
        .and_then(|v| v.as_array())
        .unwrap_or_else(|| panic!("{}: missing rule_sets array", src.display()));
    let chain = doc
        .get("rules_chain")
        .and_then(|v| v.as_array())
        .unwrap_or_else(|| panic!("{}: missing rules_chain array", src.display()));

    let group = |key: &str| -> String {
        groups
            .get(key)
            .and_then(|v| v.as_str())
            .filter(|s| !s.is_empty())
            .unwrap_or_else(|| panic!("{}: proxy_groups.{} missing/empty", src.display(), key))
            .to_string()
    };

    let mut out = String::new();
    out.push_str(&format!(
        "// @@generated by build.rs from {} — do not edit by hand.\n",
        src.display()
    ));
    out.push_str(&format!(
        "pub const GROUP_GLOBAL: &str = \"{}\";\n",
        escape(&group("global"))
    ));
    out.push_str(&format!(
        "pub const GROUP_LADDER: &str = \"{}\";\n",
        escape(&group("ladder"))
    ));
    out.push_str(&format!(
        "pub const GROUP_AI: &str = \"{}\";\n",
        escape(&group("ai"))
    ));
    out.push_str(&format!(
        "pub const GROUP_MEDIA: &str = \"{}\";\n",
        escape(&group("media"))
    ));
    out.push_str(&format!(
        "pub const GROUP_MANUAL: &str = \"{}\";\n",
        escape(&group("manual"))
    ));
    out.push_str(&format!(
        "pub const GROUP_AUTO: &str = \"{}\";\n",
        escape(&group("auto"))
    ));

    out.push_str("pub const BUILTIN_RULE_SETS_SHARED: &[&str] = &[\n");
    for rs in rule_sets {
        let name = rs
            .as_str()
            .unwrap_or_else(|| panic!("{}: rule_sets entry not a string", src.display()));
        out.push_str(&format!("    \"{}\",\n", escape(name)));
    }
    out.push_str("];\n");

    out.push_str("pub const RULES_CHAIN_TEMPLATES: &[&str] = &[\n");
    for r in chain {
        let rule = r
            .as_str()
            .unwrap_or_else(|| panic!("{}: rules_chain entry not a string", src.display()));
        out.push_str(&format!("    \"{}\",\n", escape(rule)));
    }
    out.push_str("];\n");

    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR"));
    fs::write(out_dir.join("product_data.rs"), out).expect("write product_data.rs");
}
